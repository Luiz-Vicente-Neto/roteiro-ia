// Drizzle schema. After editing, run `pnpm db:generate` to create the migration.
// These are storage types: the catalog module never sees them, the Postgres
// adapter (base-postgres.ts) translates them to the domain types.
import { sql } from "drizzle-orm";
import {
  bigint,
  boolean,
  check,
  date,
  foreignKey,
  index,
  integer,
  jsonb,
  numeric,
  pgTable,
  primaryKey,
  text,
  timestamp,
} from "drizzle-orm/pg-core";

export const destinos = pgTable("destinos", {
  slug: text().primaryKey(),
  nome: text().notNull(),
});

export const hoteis = pgTable("hoteis", {
  slug: text().primaryKey(),
  nome: text().notNull(),
  destino: text()
    .notNull()
    .references(() => destinos.slug),
  aceitaPet: boolean("aceita_pet").notNull(),
});

export const pacotes = pgTable(
  "pacotes",
  {
    slug: text().primaryKey(),
    nome: text().notNull(),
    hotel: text()
      .notNull()
      .references(() => hoteis.slug),
    noites: integer().notNull(),
    inclui: text().array().notNull(),
    // Centavos, always whole reais.
    precoBase: integer("preco_base").notNull(),
    // When true, faixas_de_criancas holds one faixa per child age (0 to 11).
    aceitaCriancas: boolean("aceita_criancas").notNull(),
  },
  (t) => [
    check("pacotes_noites_positivas", sql`${t.noites} > 0`),
    check(
      "pacotes_preco_base_em_reais_inteiros",
      sql`${t.precoBase} > 0 and ${t.precoBase} % 100 = 0`,
    ),
  ],
);

export const faixasDeCriancas = pgTable(
  "faixas_de_criancas",
  {
    pacote: text()
      .notNull()
      .references(() => pacotes.slug),
    idadeMinima: integer("idade_minima").notNull(),
    idadeMaxima: integer("idade_maxima").notNull(),
    // Whole percent of the adult price.
    percentual: integer().notNull(),
  },
  (t) => [
    primaryKey({ columns: [t.pacote, t.idadeMinima] }),
    check(
      "faixas_de_criancas_idades_de_crianca",
      sql`0 <= ${t.idadeMinima} and ${t.idadeMinima} <= ${t.idadeMaxima} and ${t.idadeMaxima} <= 11`,
    ),
    check(
      "faixas_de_criancas_percentual_valido",
      sql`${t.percentual} between 0 and 100`,
    ),
  ],
);

export const saidas = pgTable(
  "saidas",
  {
    pacote: text()
      .notNull()
      .references(() => pacotes.slug),
    // String mode: a calendar date, never shifted by a time zone.
    data: date({ mode: "string" }).notNull(),
    vagasTotais: integer("vagas_totais").notNull(),
  },
  (t) => [
    primaryKey({ columns: [t.pacote, t.data] }),
    check("saidas_vagas_nao_negativas", sql`${t.vagasTotais} >= 0`),
  ],
);

export const periodosTarifarios = pgTable(
  "periodos_tarifarios",
  {
    // Storage-only key: the domain identifies a Período by its fields.
    id: integer().primaryKey().generatedAlwaysAsIdentity(),
    nome: text().notNull(),
    tipo: text({ enum: ["temporada", "feriado"] }).notNull(),
    // Set only for a temporada; a feriado nacional counts for every Destino.
    destino: text().references(() => destinos.slug),
    inicio: date({ mode: "string" }).notNull(),
    fim: date({ mode: "string" }).notNull(),
    // Two decimals, so the price rule can multiply on integers.
    fator: numeric({ precision: 4, scale: 2, mode: "number" }).notNull(),
  },
  (t) => [
    check(
      "periodos_tarifarios_tipo_valido",
      sql`${t.tipo} in ('temporada', 'feriado')`,
    ),
    check(
      "periodos_tarifarios_destino_so_na_temporada",
      sql`(${t.tipo} = 'temporada') = (${t.destino} is not null)`,
    ),
    check(
      "periodos_tarifarios_fim_depois_do_inicio",
      sql`${t.fim} >= ${t.inicio}`,
    ),
    check("periodos_tarifarios_fator_positivo", sql`${t.fator} > 0`),
  ],
);

export const propostas = pgTable(
  "propostas",
  {
    // Random and long, generated by the catalog module, never by the database.
    id: text().primaryKey(),
    pacote: text().notNull(),
    data: date({ mode: "string" }).notNull(),
    adultos: integer().notNull(),
    // Each child's age, in the order the Grupo gave them.
    criancas: integer().array().notNull(),
    // Centavos.
    total: integer().notNull(),
    criadaEm: timestamp("criada_em", { withTimezone: true }).notNull(),
    expiraEm: timestamp("expira_em", { withTimezone: true }).notNull(),
    // Set in the same transaction that records its Pré-reserva.
    confirmada: boolean().notNull().default(false),
  },
  (t) => [
    foreignKey({
      columns: [t.pacote, t.data],
      foreignColumns: [saidas.pacote, saidas.data],
    }),
    check("propostas_ao_menos_um_adulto", sql`${t.adultos} >= 1`),
    check("propostas_total_nao_negativo", sql`${t.total} >= 0`),
    check(
      "propostas_expira_depois_de_criada",
      sql`${t.expiraEm} > ${t.criadaEm}`,
    ),
  ],
);

// No personal data on purpose: no name, e-mail or phone (docs/adr/0003).
export const preReservas = pgTable(
  "pre_reservas",
  {
    // RT-XXXX, generated by the catalog module.
    codigo: text().primaryKey(),
    // The Proposta it was made from: each Proposta makes at most one. Null
    // only for Pré-reservas recorded before this column existed.
    proposta: text()
      .unique()
      .references(() => propostas.id),
    pacote: text().notNull(),
    data: date({ mode: "string" }).notNull(),
    adultos: integer().notNull(),
    // Each child's age, in the order the Grupo gave them.
    criancas: integer().array().notNull(),
    // Centavos.
    total: integer().notNull(),
    criadaEm: timestamp("criada_em", { withTimezone: true }).notNull(),
    expiraEm: timestamp("expira_em", { withTimezone: true }).notNull(),
  },
  (t) => [
    foreignKey({
      columns: [t.pacote, t.data],
      foreignColumns: [saidas.pacote, saidas.data],
    }),
    // Counting the Vagas held on a Saída reads by these columns.
    index("pre_reservas_saida_idx").on(t.pacote, t.data, t.expiraEm),
    check("pre_reservas_ao_menos_um_adulto", sql`${t.adultos} >= 1`),
    check("pre_reservas_total_nao_negativo", sql`${t.total} >= 0`),
    check(
      "pre_reservas_expira_depois_de_criada",
      sql`${t.expiraEm} > ${t.criadaEm}`,
    ),
  ],
);

// Conversas belong to an anonymous browser id, never to a person: no login,
// no personal data.
export const conversas = pgTable(
  "conversas",
  {
    // Random, generated by the assistente module.
    id: text().primaryKey(),
    dono: text().notNull(),
    titulo: text().notNull().default(""),
    criadaEm: timestamp("criada_em", { withTimezone: true }).notNull(),
    ultimaAtividade: timestamp("ultima_atividade", {
      withTimezone: true,
    }).notNull(),
  },
  // Listing a dono's Conversas, most recent first, reads by these columns.
  (t) => [index("conversas_dono_idx").on(t.dono, t.ultimaAtividade)],
);

export const itensDeConversa = pgTable(
  "itens_de_conversa",
  {
    // Storage-only key that keeps the items in the order they were added.
    posicao: bigint({ mode: "number" })
      .primaryKey()
      .generatedAlwaysAsIdentity(),
    // Deleting a Conversa deletes its items, never its Propostas or Pré-reservas.
    conversa: text()
      .notNull()
      .references(() => conversas.id, { onDelete: "cascade" }),
    tipo: text({ enum: ["mensagem", "evento"] }).notNull(),
    // The message's or the Evento's id.
    id: text().notNull(),
    criadoEm: timestamp("criado_em", { withTimezone: true }).notNull(),
    // The UIMessage, or the Evento.
    conteudo: jsonb().notNull(),
  },
  (t) => [
    index("itens_de_conversa_conversa_idx").on(t.conversa, t.posicao),
    check(
      "itens_de_conversa_tipo_valido",
      sql`${t.tipo} in ('mensagem', 'evento')`,
    ),
  ],
);
